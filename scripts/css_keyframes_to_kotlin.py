"""One-off: turn the block loader's CSS @keyframes (from the design canvas) into a Kotlin table.

The design (data/ui_design, claude.ai canvas "GeneratingBlocks") animates 4 blocks along one 26.64 s path (`hop4`),
phase-shifted by animation-delay. This reads that stylesheet and writes android/.../hairstyle/BlockPath.kt with one flat
FloatArray: [t(0..1), x(px), y(px), rotation(deg), brightness] per keyframe, in the 200x225 box of the design.

Rotation is unwrapped to the shortest turn between keyframes: the CSS goes 324deg -> 0deg (= 360) and would spin
backwards through 324 degrees in 60 ms if it were interpolated literally.

usage: python scripts/css_keyframes_to_kotlin.py <stylesheet.css> [out.kt]
"""
import re
import sys
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "android/hairtryon/app/src/main/java/com/vto/hairtryon/hairstyle/BlockPath.kt"


def main() -> None:
    css = Path(sys.argv[1]).read_text(encoding="utf-8")
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    duration = float(re.search(r"animation:hop4 ([\d.]+)s", css).group(1))
    delays = [float(d) for d in re.findall(r"\.e\d\{animation-delay:(-?[\d.]+)s\}", css)]
    frames = re.findall(
        r"([\d.]+)%\{transform:translate\(([-\d.]+)px,([-\d.]+)px\) rotate\(([-\d.]+)deg\);filter:brightness\(([\d.]+)\)", css
    )
    assert frames and len(delays) == 4, (len(frames), delays)

    rows, prev = [], None
    for pct, x, y, rot, bright in frames:
        r = float(rot)
        if prev is not None:
            r = prev + ((r - prev + 180.0) % 360.0 - 180.0)  # shortest way round
        prev = r
        rows.append((float(pct) / 100.0, float(x), float(y), r, float(bright)))

    phases = [(-d) / duration for d in delays]  # a negative delay starts that block partway along the path
    body = ",\n".join("        " + ", ".join(f"{v:g}f" for v in row) for row in rows)
    out.write_text(
        f"""package com.vto.hairtryon.hairstyle

// Generated by scripts/css_keyframes_to_kotlin.py from the design's block loader. Do not edit by hand.

/** One loop of the 4-block hop path: [t, x, y, rotation, brightness] per keyframe, in a 200x225 box, 30x30 blocks. */
object BlockPath {{
    const val SECONDS = {duration:g}f
    val PHASES = floatArrayOf({", ".join(f"{p:g}f" for p in phases)})
    const val STRIDE = 5
    val FRAMES = floatArrayOf(
{body},
    )
}}
""",
        encoding="utf-8",
    )
    print(f"{len(rows)} keyframes, {duration} s loop, phases {phases} -> {out}")


if __name__ == "__main__":
    main()
